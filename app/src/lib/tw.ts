const NAMED: Record<string, string> = { white: '#ffffff', black: '#000000', 'muted-foreground': '#878792', primary: '#561a8e' };

function withAlpha(hex: string, alphaPct?: string) {
  if (!alphaPct) return hex;
  const a = Math.round((Number(alphaPct) / 100) * 255);
  return hex + a.toString(16).padStart(2, '0');
}

/** "text-cyan-300" -> "#67e8f9"; "bg-yellow-500/15" -> "#eab30826". undefined se non riconosciuta. */
export function twColor(cls: string): string | undefined {
  const m = cls.match(/^(?:text|bg|border|fill|ring|from|to)-([a-z]+(?:-foreground)?)(?:-(\d{2,3}))?(?:\/(\d{1,3}))?$/);
  if (!m) return undefined;
  const [, family, shade, alpha] = m;
  const hex = shade ? P[family]?.[Number(shade)] : NAMED[family];
  return hex ? withAlpha(hex, alpha) : undefined;
}

/** Estrae { color, backgroundColor, borderColor } da una stringa di classi. */
export function twColors(classes: string) {
  const out: { color?: string; backgroundColor?: string; borderColor?: string } = {};
  for (const cls of classes.split(/\s+/)) {
    const c = twColor(cls);
    if (!c) continue;
    if (cls.startsWith('text-')) out.color = c;
    else if (cls.startsWith('bg-')) out.backgroundColor = c;
    else if (cls.startsWith('border-')) out.borderColor = c;
  }
  return out;
}
